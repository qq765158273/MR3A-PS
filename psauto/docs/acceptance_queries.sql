-- Read-only HRDEV acceptance through dbx; these queries are not part of GUI MCP execution.
SELECT FIELDNAME, FIELDTYPE, LENGTH, LASTUPDDTTM
  FROM PSDBFIELD
 WHERE FIELDNAME IN ('GM_MCP_EMPLID', 'GM_MCP_FLD11', 'GM_MCP_FLD12', 'GM_MCP_FLD13')
 ORDER BY FIELDNAME;

SELECT FIELDNAME, LABEL_ID, LONGNAME, SHORTNAME, DEFAULT_LABEL
  FROM PSDBFLDLABL
 WHERE FIELDNAME IN ('GM_MCP_EMPLID', 'GM_MCP_FLD11', 'GM_MCP_FLD12', 'GM_MCP_FLD13')
 ORDER BY FIELDNAME, LABEL_ID;

SELECT RECNAME, RECTYPE, FIELDCOUNT, INDEXCOUNT
  FROM PSRECDEFN
 WHERE RECNAME IN ('GM_MCP_REC', 'GM_MCP_REC2', 'GM_MCP_REC3', 'GM_MCP_REC4')
 ORDER BY RECNAME;

SELECT RECNAME, FIELDNUM, FIELDNAME,
       CASE WHEN BITAND(USEEDIT, 1) = 1 THEN 'Y' ELSE 'N' END AS KEY_FLAG,
       CASE WHEN BITAND(USEEDIT, 2048) = 2048 THEN 'Y' ELSE 'N' END AS SEARCH_KEY,
       CASE WHEN BITAND(USEEDIT, 16) = 16 THEN 'Y' ELSE 'N' END AS ALT_SEARCH_KEY,
       CASE WHEN BITAND(USEEDIT, 32) = 32 THEN 'Y' ELSE 'N' END AS LISTBOX
  FROM PSRECFIELD
 WHERE RECNAME IN ('GM_MCP_REC', 'GM_MCP_REC2', 'GM_MCP_REC3', 'GM_MCP_REC4')
 ORDER BY RECNAME, FIELDNUM;

SELECT TABLE_NAME, COLUMN_ID, COLUMN_NAME, DATA_TYPE, CHAR_LENGTH, NULLABLE
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME IN ('PS_GM_MCP_REC', 'PS_GM_MCP_REC2', 'PS_GM_MCP_REC3', 'PS_GM_MCP_REC4')
 ORDER BY TABLE_NAME, COLUMN_ID;

SELECT TABLE_NAME, INDEX_NAME, UNIQUENESS, STATUS
  FROM USER_INDEXES
 WHERE TABLE_NAME IN ('PS_GM_MCP_REC', 'PS_GM_MCP_REC2', 'PS_GM_MCP_REC3', 'PS_GM_MCP_REC4')
 ORDER BY TABLE_NAME, INDEX_NAME;

SELECT 'GM_MCP_REC' AS RECNAME, COUNT(*) AS ROW_COUNT FROM PS_GM_MCP_REC
UNION ALL
SELECT 'GM_MCP_REC3', COUNT(*) FROM PS_GM_MCP_REC3
UNION ALL
SELECT 'GM_MCP_REC4', COUNT(*) FROM PS_GM_MCP_REC4;

SELECT AE_APPLID, AE_SECTION, AE_STEP, AE_SEQ_NUM, AE_ACTIVE_STATUS
  FROM PSAESTEPDEFN
 WHERE AE_APPLID IN ('GM_MCP_AE', 'GM_MCP_AE2', 'GM_MCP_AE3', 'GM_MCP_AE4')
 ORDER BY AE_APPLID, AE_SEQ_NUM;

SELECT S.AE_APPLID, S.AE_SECTION, S.AE_STEP, S.AE_STMT_TYPE,
       T.SQLID, T.SEQNUM, T.SQLTEXT
  FROM PSAESTMTDEFN S
  LEFT JOIN PSSQLTEXTDEFN T ON T.SQLID = S.SQLID
 WHERE S.AE_APPLID IN ('GM_MCP_AE', 'GM_MCP_AE2', 'GM_MCP_AE3', 'GM_MCP_AE4')
 ORDER BY S.AE_APPLID, S.AE_STEP, S.AE_STMT_TYPE, T.SEQNUM;

SELECT OBJECTVALUE1 AS AE_APPLID, OBJECTVALUE2 AS SECTION_NAME,
       OBJECTVALUE6 AS STEP_NAME, PROGSEQ, PCTEXT
  FROM PSPCMTXT
 WHERE OBJECTID1 = 66 AND OBJECTVALUE1 IN ('GM_MCP_AE', 'GM_MCP_AE2', 'GM_MCP_AE3', 'GM_MCP_AE4')
 ORDER BY OBJECTVALUE1, OBJECTVALUE6, PROGSEQ;

SELECT OBJECTVALUE1 AS AE_APPLID, OBJECTVALUE6 AS STEP_NAME,
       PROGSEQ, PROGLEN, LASTUPDDTTM
  FROM PSPCMPROG
 WHERE OBJECTID1 = 66 AND OBJECTVALUE1 IN ('GM_MCP_AE', 'GM_MCP_AE2', 'GM_MCP_AE3', 'GM_MCP_AE4')
 ORDER BY OBJECTVALUE1, OBJECTVALUE6, PROGSEQ;
